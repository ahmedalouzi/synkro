import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { flutterLayoutIssues, parsePreviewRuntimeReport, type FlutterLayoutMeasurement } from '@peep/shared';
import { FLUTTER_SYSTEM_PROMPT } from '../src/prompts/flutter-system';
import { PREVIEW_ENTRY, mainTakesArgs, previewEntrySource, pubspecName, writePreviewEntry } from '../../../apps/desktop/src/main/services/flutter-preview-entry';
import { runFlutterHarness, type HarnessDevice } from './fixtures/flutter-safe-area/run-harness';

/**
 * A user's Flutter preview (iPhone 15 frame): the header under the status bar / Dynamic Island, and a 7-item bottom
 * navigation with cut labels down at the home indicator. Flutter web gets no safe-area insets in a browser
 * (MediaQuery padding 0 on every device), so Scaffold / AppBar / SafeArea could not keep clear of them. The preview now
 * runs the app through an entrypoint that gives it the device's insets and measures the screen for the agent.
 *
 * With SYNKRO_RUN_FLUTTER_TESTS=1 (Windows/macOS, Docker with synkro/flutter-sandbox:2, network for pub): builds the
 * fixture app with Flutter 3.44 and runs it in Electron with the real preload, per device.
 */
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../../..');

// Measured from the fixture (iPhone 17 Pro, 402 x 874, insets 62 / 34).
const GOOD: FlutterLayoutMeasurement = {
  innerHeight: 874, insetTop: 62, insetBottom: 34, navItems: 4,
  texts: [
    { top: 76, bottom: 104, appBar: true, nav: false, clipped: false },
    { top: 427, bottom: 447, appBar: false, nav: false, clipped: false },
    { top: 806, bottom: 822, appBar: false, nav: true, clipped: false },
  ],
};
const BROKEN: FlutterLayoutMeasurement = {
  innerHeight: 874, insetTop: 62, insetBottom: 34, navItems: 7,
  texts: [
    { top: 0, bottom: 31, appBar: false, nav: false, clipped: false },
    { top: 806, bottom: 822, appBar: false, nav: true, clipped: true },
    { top: 806, bottom: 822, appBar: false, nav: true, clipped: true },
    { top: 850, bottom: 866, appBar: false, nav: false, clipped: false },
  ],
};

export default async function run() {
  console.log('  [flutter-safe] The layout check: a screen built right has no problems...');
  assert.deepEqual(flutterLayoutIssues(GOOD), []);
  assert.deepEqual(flutterLayoutIssues({ ...BROKEN, insetTop: 0, insetBottom: 0, navItems: 4, texts: BROKEN.texts.map((t) => ({ ...t, clipped: false })) }), [],
    'no insets (e.g. a browser): text at the edges is fine');

  console.log('  [flutter-safe] ...the user\'s screen has four, each with its fix...');
  const issues = flutterLayoutIssues(BROKEN);
  assert.deepEqual(issues.map((i) => i.kind), ['content-under-status-bar', 'content-under-home-indicator', 'too-many-tabs', 'tab-labels-clipped']);
  assert.match(issues[0].message, /inside the top 62 px .*Scaffold .*SafeArea/);
  assert.match(issues[1].message, /bottom 34 px .*home indicator/);
  assert.match(issues[2].message, /7 destinations; phones fit 5 at most\. .*"More" tab or a Drawer/);
  assert.match(issues[3].message, /2 bottom-navigation label\(s\) do not fit/);
  const inPage = new Function(`return (${flutterLayoutIssues.toString()})`)() as typeof flutterLayoutIssues;
  assert.deepEqual(inPage(BROKEN), issues, 'self-contained (runs in the page)');
  assert.deepEqual(inPage({ innerHeight: 800, insetTop: 40, insetBottom: 20, navItems: 0, texts: 'x' as any }), [], 'bad input: nothing');
  const base = { errors: [], rendered: true, textChars: 10, overlay: '' };
  assert.deepEqual(parsePreviewRuntimeReport({ ...base, layout: issues })?.layout, issues, 'the new kinds reach the agent');

  console.log('  [flutter-safe] The preview entrypoint...');
  assert.equal(pubspecName('name: my_app\ndescription: x\n'), 'my_app');
  assert.equal(pubspecName('description: x\n'), null);
  assert.equal(mainTakesArgs('void main(List<String> args) {}'), true);
  assert.equal(mainTakesArgs('Future<void> main() async {}'), false);
  const src = previewEntrySource('my_app', false);
  assert.match(src, /^\/\/ Generated by Atomvs for the live preview only/);
  assert.match(src, /import 'package:my_app\/main\.dart' as app;/);
  assert.match(src, /_AtomvsPreviewBinding\(\);\n  _atomvsCaptureFlutterErrors\(\);\n  app\.main\(\);/);
  assert.match(previewEntrySource('my_app', true), /app\.main\(const <String>\[\]\);/);
  assert.match(src, /Widget wrapWithDefaultView\(Widget rootWidget\) =>\s+super\.wrapWithDefaultView\(_AtomvsSafeArea\(child: rootWidget\)\);/);
  assert.match(src, /--atomvs-safe-area-inset-\$name/, 'reads the shim\'s CSS variables');
  assert.match(src, /mq\.copyWith\(viewPadding: viewPadding, padding: padding\)/);
  assert.match(src, /globalContext\['__atomvsFlutterLayout'\] = report\.jsify\(\);/);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'flutter-entry-'));
  try {
    fs.mkdirSync(path.join(tmp, 'lib'));
    fs.writeFileSync(path.join(tmp, 'pubspec.yaml'), 'name: shop_app\n');
    fs.writeFileSync(path.join(tmp, 'lib', 'main.dart'), 'void main() => runApp(const App());\n');
    assert.equal(await writePreviewEntry(tmp), PREVIEW_ENTRY);
    assert.match(fs.readFileSync(path.join(tmp, PREVIEW_ENTRY), 'utf8'), /package:shop_app\/main\.dart/);
    assert.equal(PREVIEW_ENTRY.startsWith('.dart_tool/'), true, 'in Flutter\'s own git-ignored folder, not in the app');
    fs.rmSync(path.join(tmp, 'lib', 'main.dart'));
    assert.equal(await writePreviewEntry(tmp), null, 'no lib/main.dart: the plain run');
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  const service = fs.readFileSync(path.join(root, 'apps/desktop/src/main/services/flutter-service.ts'), 'utf8');
  assert.match(service, /const target = await writePreviewEntry\(flutterRoot\);/);
  assert.match(service, /'--web-hostname', '127\.0\.0\.1', \.\.\.\(target \? \['-t', target\] : \[\]\)\]/);
  const shim = ['preview-safe-area.ts', 'preview-safe-area-page.ts']
    .map((f) => fs.readFileSync(path.join(root, 'apps/desktop/src/preload', f), 'utf8')).join('\n');
  assert.match(shim, /\$\{flutterLayoutIssues\.toString\(\)\}\);`/);
  assert.match(shim, /'atomvs:flutter-layout'\]\) window\.addEventListener\(type, schedule\)/);

  console.log('  [flutter-safe] The agent: Scaffold / SafeArea, at most 5 tabs, labels that fit...');
  assert.match(FLUTTER_SYSTEM_PROMPT, /\*\*SAFE AREAS \(Flutter\)\*\*: .*Build every screen with a Scaffold.*wrap any other content in SafeArea/);
  assert.match(FLUTTER_SYSTEM_PROMPT, /at most 5 destinations; put the rest in a "More" tab or a Drawer\. Labels must fit on one line/);

  if (process.env.SYNKRO_RUN_FLUTTER_TESTS !== '1') {
    console.log('  (skipped the Flutter build + Electron run: set SYNKRO_RUN_FLUTTER_TESTS=1)');
    console.log('  🟢 Flutter safe-area tests passed.');
    return;
  }

  console.log('  [flutter-safe] Building the fixture with Flutter 3.44 (plain, and through the entrypoint: good / broken)...');
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'flutter-safe-build-'));
  try {
    const fixture = path.join(root, 'packages/agent/tests/fixtures/flutter-safe-area');
    fs.cpSync(path.join(fixture, 'lib'), path.join(work, 'src', 'lib'), { recursive: true });
    fs.copyFileSync(path.join(fixture, 'pubspec.yaml'), path.join(work, 'src', 'pubspec.yaml'));
    fs.mkdirSync(path.join(work, 'src', '.dart_tool', 'atomvs_preview'), { recursive: true });
    fs.writeFileSync(path.join(work, 'src', PREVIEW_ENTRY), previewEntrySource('safe_area_fixture', false));
    const script = [
      'cp -r /out/src /tmp/app && cd /tmp/app && flutter create --platforms web --org com.atomvs.fixture . >/dev/null 2>&1',
      'flutter build web --release --no-web-resources-cdn --no-wasm-dry-run >/dev/null && cp -r build/web /out/plain',
      ...['good', 'broken'].map((m) => `flutter build web --release --no-web-resources-cdn --no-wasm-dry-run -t ${PREVIEW_ENTRY} --dart-define=MODE=${m} >/dev/null && cp -r build/web /out/${m}`),
    ].join(' && ');
    const build = spawnSync('docker', ['run', '--rm', '-v', `${work}:/out`, 'synkro/flutter-sandbox:2', 'sh', '-c', script], { encoding: 'utf8', timeout: 600_000, env: { ...process.env, MSYS_NO_PATHCONV: '1' } });
    assert.equal(build.status, 0, `flutter build failed: ${build.stderr?.slice(-2000)}`);

    const devices: HarnessDevice[] = [
      { id: 'iphone-17-pro', width: 402, height: 874, insets: { top: 62, right: 0, bottom: 34, left: 0 } },
      { id: 'iphone-15', width: 393, height: 852, insets: { top: 59, right: 0, bottom: 34, left: 0 } },
      { id: 'pixel-8', width: 412, height: 915, insets: { top: 36, right: 0, bottom: 24, left: 0 } },
      { id: 'pixel-fold', width: 412, height: 870, insets: { top: 28, right: 0, bottom: 20, left: 0 } },
      { id: 'iphone-se', width: 375, height: 667, insets: { top: 20, right: 0, bottom: 0, left: 0 } },
    ];
    console.log('  [flutter-safe] Without the entrypoint, Flutter web gets no insets (the bug)...');
    const plain = await runFlutterHarness(root, path.join(work, 'plain'), devices);
    for (const d of devices) assert.deepEqual(plain[d.id]?.padding, [0, 0, 0, 0], `${d.id}: plain Flutter web sees 0`);

    console.log('  [flutter-safe] With it: the device\'s insets, the header below the status bar, no problems...');
    const good = await runFlutterHarness(root, path.join(work, 'good'), devices);
    for (const d of devices) {
      const r = good[d.id]!;
      assert.deepEqual(r.padding, [d.insets.top, d.insets.bottom, 0, 0], `${d.id}: MediaQuery.padding`);
      assert.ok(r.title[0] >= d.insets.top, `${d.id}: the AppBar title (${r.title[0]}) is below the status bar (${d.insets.top})`);
      assert.equal(Math.round(r.nav[1]), d.height, `${d.id}: the NavigationBar reaches the bottom edge (its background)`);
      assert.ok(r.nav[1] - r.nav[0] >= 80 + d.insets.bottom - 1, `${d.id}: and grows by the home-indicator inset`);
      assert.deepEqual(r.runtime?.layout, [], `${d.id}: no layout problems`);
    }

    console.log('  [flutter-safe] ...and the user\'s broken screen is reported to the agent on every device...');
    const broken = await runFlutterHarness(root, path.join(work, 'broken'), devices);
    for (const d of devices) {
      const kinds = broken[d.id]!.runtime?.layout.map((l) => l.kind) ?? [];
      assert.ok(kinds.includes('content-under-status-bar'), `${d.id}: header under the status bar (${kinds})`);
      assert.ok(kinds.includes('too-many-tabs'), `${d.id}: 7 tabs`);
      assert.ok(kinds.includes('tab-labels-clipped'), `${d.id}: cut labels`);
    }
  } finally {
    try {
      fs.rmSync(work, { recursive: true, force: true });
    } catch {
      // Docker may still hold the folder for a moment.
    }
  }
  console.log('  🟢 Flutter safe-area tests passed.');
}
