import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * Flutter web draws on a canvas and gets no safe-area insets in a browser: MediaQuery padding and viewPadding are 0,
 * so in the phone frame an AppBar sits under the status bar / Dynamic Island and a NavigationBar under the home
 * indicator, while on a real phone Scaffold and SafeArea keep them clear. The preview therefore runs the app through
 * a small entrypoint of its own (never part of the app or its builds):
 *
 * - a binding whose wrapWithDefaultView puts a MediaQuery with the device's insets above the app. The insets come
 *   from the preview shim (the --atomvs-safe-area-inset-* CSS variables it sets, and its atomvs:safe-area messages
 *   when the device or orientation changes);
 * - a layout probe: where text sits relative to the insets, how many bottom-navigation destinations there are and
 *   whether their labels fit. It sets window.__atomvsFlutterLayout for the shim, which reports layout problems to
 *   the agent like the React Native tab-bar check (flutterLayoutIssues in @peep/shared).
 *
 * The file goes to .dart_tool/atomvs_preview/main.dart (.dart_tool is Flutter's own, git-ignored folder) and is run
 * with `flutter run -t`. Hot reload still reloads the app's files, which it imports.
 */

export const PREVIEW_ENTRY = '.dart_tool/atomvs_preview/main.dart';

/** The app's package name (pubspec.yaml `name:`), or null. Exported for tests. */
export function pubspecName(pubspec: string): string | null {
  return /^name:\s*([a-z_][a-z0-9_]*)\s*$/m.exec(pubspec)?.[1] ?? null;
}

/** Whether lib/main.dart's main takes arguments (`main(List<String> args)`). Exported for tests. */
export function mainTakesArgs(mainDart: string): boolean {
  return /\bmain\s*\(\s*List\s*<\s*String\s*>/.test(mainDart);
}

/** The entrypoint's Dart source. Exported for tests. */
export function previewEntrySource(packageName: string, takesArgs: boolean): string {
  return `// Generated by Atomvs for the live preview only: not part of your app or its builds. Do not edit.
// Gives the app the phone's safe-area insets (Flutter web gets none in a browser) and reports layout problems.
import 'dart:async';
import 'dart:js_interop';
import 'dart:js_interop_unsafe';
import 'dart:math' as math;

import 'package:flutter/cupertino.dart';
import 'package:flutter/material.dart';
import 'package:flutter/rendering.dart';
import 'package:${packageName}/main.dart' as app;

void main() {
  _AtomvsPreviewBinding();
  app.main(${takesArgs ? 'const <String>[]' : ''});
}

class _AtomvsPreviewBinding extends WidgetsFlutterBinding {
  @override
  Widget wrapWithDefaultView(Widget rootWidget) =>
      super.wrapWithDefaultView(_AtomvsSafeArea(child: rootWidget));
}

EdgeInsets _cssInsets() {
  try {
    final root = (globalContext['document'] as JSObject)['documentElement'];
    final style = globalContext.callMethod<JSObject>('getComputedStyle'.toJS, root);
    double side(String name) {
      final value = style.callMethod<JSString>('getPropertyValue'.toJS, '--atomvs-safe-area-inset-$name'.toJS).toDart;
      final v = double.tryParse(value.replaceAll('px', '').trim()) ?? 0;
      return v.isFinite && v >= 0 && v <= 200 ? v : 0;
    }
    return EdgeInsets.fromLTRB(side('left'), side('top'), side('right'), side('bottom'));
  } catch (_) {
    return EdgeInsets.zero;
  }
}

class _AtomvsSafeArea extends StatefulWidget {
  const _AtomvsSafeArea({required this.child});
  final Widget child;

  @override
  State<_AtomvsSafeArea> createState() => _AtomvsSafeAreaState();
}

class _AtomvsSafeAreaState extends State<_AtomvsSafeArea> {
  EdgeInsets insets = _cssInsets();
  JSFunction? onMessage;
  Timer? probe;
  String lastReport = '';
  FlutterExceptionHandler? _prevOnError;
  int overflowErrors = 0;

  @override
  void initState() {
    super.initState();
    _prevOnError = FlutterError.onError;
    FlutterError.onError = (FlutterErrorDetails details) {
      if (details.exceptionAsString().contains('RenderFlex overflowed by')) {
        overflowErrors++;
      }
      _prevOnError?.call(details);
    };
    // The device or orientation changed: the shim has set the new values as CSS variables.
    onMessage = ((JSObject event) {
      final data = event['data'];
      if (data == null || !data.isA<JSObject>()) return;
      final type = (data as JSObject)['type'];
      if (type == null || !type.isA<JSString>() || (type as JSString).toDart != 'atomvs:safe-area') return;
      Timer(const Duration(milliseconds: 30), () {
        if (mounted) setState(() => insets = _cssInsets());
      });
    }).toJS;
    globalContext.callMethod('addEventListener'.toJS, 'message'.toJS, onMessage);
    probe = Timer.periodic(const Duration(milliseconds: 700), (_) => _probe());
  }

  @override
  void dispose() {
    if (_prevOnError != null) {
      FlutterError.onError = _prevOnError;
    }
    globalContext.callMethod('removeEventListener'.toJS, 'message'.toJS, onMessage);
    probe?.cancel();
    super.dispose();
  }

  void _probe() {
    try {
      final root = WidgetsBinding.instance.rootElement;
      if (root == null || !mounted) return;
      final size = MediaQuery.sizeOf(context);
      final texts = <Map<String, Object>>[];
      var navItems = 0;
      void visit(Element element, bool inAppBar, bool inNav) {
        final widget = element.widget;
        if (widget is AppBar || widget is SliverAppBar || widget is CupertinoNavigationBar) inAppBar = true;
        if (widget is NavigationBar) { inNav = true; navItems = math.max(navItems, widget.destinations.length); }
        if (widget is BottomNavigationBar) { inNav = true; navItems = math.max(navItems, widget.items.length); }
        if (widget is CupertinoTabBar) { inNav = true; navItems = math.max(navItems, widget.items.length); }
        if (widget is Offstage && widget.offstage) return;
        if (widget is Visibility && !widget.visible) return;
        // Only the element that owns the RenderParagraph (a Text's renderObject is its RichText child's: counted once).
        final render = element is RenderObjectElement ? element.renderObject : null;
        if (render is RenderParagraph && render.attached && render.hasSize && render.size.width > 0) {
          final topLeft = render.localToGlobal(Offset.zero);
          final top = topLeft.dy, bottom = topLeft.dy + render.size.height;
          if (bottom > 0 && top < size.height && topLeft.dx < size.width && topLeft.dx + render.size.width > 0) {
            final fullWidth = render.getMaxIntrinsicWidth(double.infinity);
            texts.add({
              'top': top, 'bottom': bottom, 'appBar': inAppBar, 'nav': inNav,
              'clipped': render.didExceedMaxLines || (inNav && fullWidth > render.size.width + 1),
            });
          }
        }
        element.visitChildElements((child) => visit(child, inAppBar, inNav));
      }
      root.visitChildElements((child) => visit(child, false, false));
      final report = <String, Object>{
        'innerHeight': size.height,
        'insetTop': insets.top,
        'insetBottom': insets.bottom,
        'navItems': navItems,
        'overflowErrors': overflowErrors,
        'texts': texts.take(400).toList(),
      };
      final json = report.toString();
      if (json == lastReport) return;
      lastReport = json;
      globalContext['__atomvsFlutterLayout'] = report.jsify();
      globalContext.callMethod('dispatchEvent'.toJS,
          (globalContext['Event'] as JSFunction).callAsConstructor<JSObject>('atomvs:flutter-layout'.toJS));
    } catch (_) {
      // Never break the app over a measurement.
    }
  }

  @override
  Widget build(BuildContext context) {
    return MediaQuery.fromView(
      view: View.of(context),
      child: Builder(builder: (context) {
        final mq = MediaQuery.of(context);
        final viewPadding = EdgeInsets.fromLTRB(
          math.max(mq.viewPadding.left, insets.left), math.max(mq.viewPadding.top, insets.top),
          math.max(mq.viewPadding.right, insets.right), math.max(mq.viewPadding.bottom, insets.bottom));
        final padding = EdgeInsets.fromLTRB(viewPadding.left, viewPadding.top, viewPadding.right,
            math.max(0, viewPadding.bottom - mq.viewInsets.bottom));
        return MediaQuery(data: mq.copyWith(viewPadding: viewPadding, padding: padding), child: widget.child);
      }),
    );
  }
}
`;
}

/**
 * Writes the preview entrypoint into the project's .dart_tool and returns its path for `flutter run -t`, or null
 * (no lib/main.dart or no package name): then the preview runs lib/main.dart as before.
 */
export async function writePreviewEntry(flutterRoot: string): Promise<string | null> {
  try {
    const name = pubspecName(await readFile(join(flutterRoot, 'pubspec.yaml'), 'utf8'));
    const mainDart = await readFile(join(flutterRoot, 'lib', 'main.dart'), 'utf8');
    if (!name || !/\bmain\s*\(/.test(mainDart)) return null;
    await mkdir(join(flutterRoot, '.dart_tool', 'atomvs_preview'), { recursive: true });
    await writeFile(join(flutterRoot, PREVIEW_ENTRY), previewEntrySource(name, mainTakesArgs(mainDart)));
    return PREVIEW_ENTRY;
  } catch {
    return null;
  }
}
